-- Tokens for scripts and tools (see ApiTokenService): each works for one board only, acts as the
-- user who created it, and can read, write or both. Only the SHA-256 of the token is stored, so a
-- database dump can't be used with them. Deleting the user or the board deletes their tokens.
CREATE TABLE api_token (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    board_id integer NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    name character varying(50) NOT NULL,
    token_hash character varying(64) NOT NULL UNIQUE,
    can_read boolean NOT NULL,
    can_write boolean NOT NULL,
    created timestamp(6) with time zone NOT NULL
);

CREATE INDEX api_token_user_board ON api_token (user_id, board_id);
