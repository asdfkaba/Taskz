-- People a board's owner invited (see BoardMemberService). Members can do everything on the board
-- except deleting it, sharing it and managing its members. Deleting the board or the user deletes
-- the membership.
CREATE TABLE board_member (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id integer NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    joined timestamp(6) with time zone NOT NULL,
    CONSTRAINT board_member_unique UNIQUE (board_id, user_id)
);

-- Open invite links: single use, valid for 7 days. Only the SHA-256 of the link's key is stored,
-- so a database dump can't be used to join boards.
CREATE TABLE board_invite (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id integer NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    token_hash character varying(64) NOT NULL UNIQUE,
    created timestamp(6) with time zone NOT NULL,
    expires timestamp(6) with time zone NOT NULL
);
