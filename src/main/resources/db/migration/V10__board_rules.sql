-- Automations the owner of a board set up (see BoardRuleService): when a task enters column_id
-- (trigger), the action runs with its settings (payload, JSON). Deleting the column deletes its rules.
CREATE TABLE board_rule (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    column_id integer NOT NULL REFERENCES board_column (id) ON DELETE CASCADE,
    trigger character varying(32) NOT NULL,
    action character varying(32) NOT NULL,
    payload text NOT NULL,
    enabled boolean NOT NULL
);
CREATE INDEX board_rule_column_id ON board_rule (column_id);
