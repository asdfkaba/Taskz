-- Files attached to a task. The files themselves live on disk (attachments.dir), named by
-- storage_key; this table holds what is needed to list and serve them.
-- Deleting a task deletes its rows (ON DELETE CASCADE); files without a row are removed by a
-- periodic cleanup in the app.
CREATE TABLE task_attachment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id integer NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    user_id integer REFERENCES "user" (id),
    file_name text NOT NULL,
    content_type character varying(100) NOT NULL,
    size bigint NOT NULL,
    storage_key character varying(36) NOT NULL UNIQUE,
    created timestamp(6) with time zone NOT NULL
);

CREATE INDEX task_attachment_task_id ON task_attachment (task_id);
