-- The checklist of a task: a flat list of items in order (see ChecklistItem). Replaces the
-- "- [ ]" lines in descriptions, which are plain text from now on. Deleting the task deletes it.
CREATE TABLE task_checklist_item (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id integer NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    text character varying(200) NOT NULL,
    checked boolean NOT NULL,
    position integer NOT NULL
);
CREATE INDEX task_checklist_item_task_id ON task_checklist_item (task_id);
