-- How a user wants notifications on a channel besides the bell (see NotificationPreferenceService).
-- No row: the channel is off. last_digest_at: when the last summary went out, or summaries were
-- switched on, so a summary only holds what came after. The unsubscribe token lets the link in a
-- mail switch the channel off without a login; it can do nothing else.
CREATE TABLE notification_preference (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    channel character varying(32) NOT NULL,
    delivery character varying(16) NOT NULL,
    last_digest_at timestamp(6) with time zone,
    unsubscribe_token character varying(64) NOT NULL UNIQUE,
    CONSTRAINT notification_preference_unique UNIQUE (user_id, channel)
);
