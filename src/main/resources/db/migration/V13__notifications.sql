-- Messages for one user, shown under the bell (see NotificationService). Board and task are
-- optional: a notification can be about a task, a board, or nothing in particular. Deleting the
-- board deletes its notifications; deleting only the task keeps them, pointing at the board.
CREATE TABLE notification (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    board_id integer REFERENCES board (id) ON DELETE CASCADE,
    task_id integer REFERENCES task (id) ON DELETE SET NULL,
    text character varying(500) NOT NULL,
    created timestamp(6) with time zone NOT NULL,
    -- seen: the bell was opened after it came, so it no longer counts there; read: the user dealt with it.
    seen_at timestamp(6) with time zone,
    read_at timestamp(6) with time zone
);

CREATE INDEX notification_user_created ON notification (user_id, created);
